#!/usr/bin/env python3
"""Generate store/README rasters and the notification bubble from the launcher mark.

Source of truth: app/src/main/res/drawable/ic_launcher_foreground.xml
Colors: commons/src/main/res/values/colors.xml (m3_primary, m3_surface, m3_on_primary)

Writes:
  graphics/icon.svg
  graphics/icon-512.png
  graphics/icon-1024.png
  graphics/icon.webp
  graphics/icon.stamp
  app/src/main/ic_launcher-playstore.png
  app/src/main/res/drawable/ic_message_bubble.xml

Pass --check to verify committed text outputs and the input stamp (stdlib only;
no Rsvg/Pillow). Rasterizer imports run only on the export write path.
"""
from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FOREGROUND = ROOT / 'app/src/main/res/drawable/ic_launcher_foreground.xml'
COLORS = ROOT / 'commons/src/main/res/values/colors.xml'
GRAPHICS = ROOT / 'graphics'
ICON_SVG = GRAPHICS / 'icon.svg'
ICON_STAMP = GRAPHICS / 'icon.stamp'
ICON_1024 = GRAPHICS / 'icon-1024.png'
ICON_512 = GRAPHICS / 'icon-512.png'
ICON_WEBP = GRAPHICS / 'icon.webp'
BUBBLE = ROOT / 'app/src/main/res/drawable/ic_message_bubble.xml'
PLAYSTORE = ROOT / 'app/src/main/ic_launcher-playstore.png'

RASTERS = (ICON_1024, ICON_512, ICON_WEBP, PLAYSTORE)

# Notification viewport crops the adaptive-icon padding around the mark path.
BUBBLE_VIEW = 76
BUBBLE_TRANSLATE = (-12, -7)

COLOR_NAMES = ('m3_primary', 'm3_surface', 'm3_on_primary')


def _attr(tag: str, name: str) -> str:
    match = re.search(rf'\bandroid:{name}="([^"]+)"', tag)
    if not match:
        raise ValueError(f'missing android:{name} in {tag[:80]}…')
    return match.group(1)


def parse_foreground(text: str) -> tuple[float, float, float, float, str]:
    """Return translateX, translateY, scaleX, scaleY, pathData from the brand vector."""
    group = re.search(r'<group\b[^>]*>', text)
    path = re.search(r'<path\b[^>]*/?>', text)
    if not group or not path:
        raise ValueError(f'{FOREGROUND.relative_to(ROOT)}: expected one <group> and one <path>')
    if len(re.findall(r'<path\b', text)) != 1:
        raise ValueError(f'{FOREGROUND.relative_to(ROOT)}: brand mark must be a single path')
    g, p = group.group(0), path.group(0)
    return (
        float(_attr(g, 'translateX')),
        float(_attr(g, 'translateY')),
        float(_attr(g, 'scaleX')),
        float(_attr(g, 'scaleY')),
        _attr(p, 'pathData'),
    )


def parse_colors(text: str) -> dict[str, str]:
    found = dict(
        re.findall(
            r'<color\s+name="(m3_(?:primary|surface|on_primary))">(#[0-9A-Fa-f]{6})</color>',
            text,
        )
    )
    for name in COLOR_NAMES:
        if name not in found:
            raise ValueError(f'{COLORS.relative_to(ROOT)}: missing {name}')
    return found


def _num(value: float) -> str:
    return str(int(value)) if value == int(value) else str(value)


def build_icon_svg(path_data: str, tx: float, ty: float, sx: float, sy: float, colors: dict[str, str]) -> str:
    transform = f'translate({_num(tx)} {_num(ty)}) scale({_num(sx)} {_num(sy)})'
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 108 108">\n'
        f'  <rect width="108" height="108" fill="{colors["m3_primary"]}"/>\n'
        f'  <g transform="{transform}">\n'
        f'    <path fill="{colors["m3_surface"]}" fill-rule="evenodd" d="{path_data}"/>\n'
        '  </g>\n'
        '</svg>\n'
    )


def build_bubble_xml(path_data: str) -> str:
    dx, dy = BUBBLE_TRANSLATE
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by tools/export_icon.py from ic_launcher_foreground.xml. Do not edit. -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="24dp"\n'
        '    android:height="24dp"\n'
        f'    android:viewportWidth="{BUBBLE_VIEW}"\n'
        f'    android:viewportHeight="{BUBBLE_VIEW}">\n'
        f'    <group android:translateX="{dx}" android:translateY="{dy}">\n'
        '        <path\n'
        '            android:fillColor="@color/m3_on_primary"\n'
        '            android:fillType="evenOdd"\n'
        f'            android:pathData="{path_data}" />\n'
        '    </group>\n'
        '</vector>\n'
    )


def input_hash(foreground_text: str, colors: dict[str, str]) -> str:
    """Stable hash of the foreground vector plus the GM3 colors the export uses."""
    digest = hashlib.sha256()
    digest.update(foreground_text.encode())
    digest.update(b'\n')
    for name in COLOR_NAMES:
        digest.update(f'{name}={colors[name]}\n'.encode())
    return digest.hexdigest()


def stamp_contents(digest: str) -> str:
    return (
        '# Generated by tools/export_icon.py. Input hash of ic_launcher_foreground.xml\n'
        '# plus m3_primary, m3_surface, m3_on_primary from colors.xml.\n'
        f'{digest}\n'
    )


def build_text_outputs(
    foreground_text: str,
    colors: dict[str, str],
) -> tuple[str, str, str]:
    tx, ty, sx, sy, path_data = parse_foreground(foreground_text)
    svg = build_icon_svg(path_data, tx, ty, sx, sy, colors)
    bubble = build_bubble_xml(path_data)
    stamp = stamp_contents(input_hash(foreground_text, colors))
    return svg, bubble, stamp


def check_exports() -> int:
    """Stdlib-only verification: text outputs + input stamp; rasters must exist."""
    foreground_text = FOREGROUND.read_text()
    colors = parse_colors(COLORS.read_text())
    expected_svg, expected_bubble, expected_stamp = build_text_outputs(foreground_text, colors)

    failed: list[str] = []
    text_outputs = {
        ICON_SVG: expected_svg,
        BUBBLE: expected_bubble,
        ICON_STAMP: expected_stamp,
    }
    for path, expected in text_outputs.items():
        if not path.exists():
            failed.append(f'missing {path.relative_to(ROOT)}')
            continue
        if path.read_text() != expected:
            failed.append(f'stale {path.relative_to(ROOT)} (run python3 tools/export_icon.py)')

    for path in RASTERS:
        if not path.exists():
            failed.append(f'missing {path.relative_to(ROOT)} (run python3 tools/export_icon.py)')

    if failed:
        print('Icon export check failed:', file=sys.stderr)
        for line in failed:
            print(f'  {line}', file=sys.stderr)
        return 1
    print('Icon export check passed')
    return 0


def write_rasters(svg: str) -> None:
    """Rasterize store/README images. Imports Rsvg/Pillow only here."""
    import gi
    gi.require_version('Rsvg', '2.0')
    from gi.repository import Rsvg
    from PIL import Image

    def render(size: int, dest: Path) -> None:
        sized = svg.replace('width="512" height="512"', f'width="{size}" height="{size}"', 1)
        Rsvg.Handle.new_from_data(sized.encode()).get_pixbuf().savev(str(dest), 'png', [], [])

    GRAPHICS.mkdir(parents=True, exist_ok=True)
    render(1024, ICON_1024)
    render(512, ICON_512)
    PLAYSTORE.write_bytes(ICON_512.read_bytes())
    with Image.open(ICON_1024) as image:
        image.resize((192, 192), Image.Resampling.LANCZOS).save(ICON_WEBP, lossless=True)


def write_exports() -> int:
    foreground_text = FOREGROUND.read_text()
    colors = parse_colors(COLORS.read_text())
    svg, bubble, stamp = build_text_outputs(foreground_text, colors)

    for path, content in (
        (ICON_SVG, svg),
        (BUBBLE, bubble),
        (ICON_STAMP, stamp),
    ):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
        print(f'wrote {path.relative_to(ROOT)}')

    write_rasters(svg)
    for path in RASTERS:
        print(f'wrote {path.relative_to(ROOT)}')
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        '--check',
        action='store_true',
        help='verify text outputs and input stamp with the stdlib only (no Rsvg/Pillow)',
    )
    args = parser.parse_args(argv)
    if args.check:
        return check_exports()
    return write_exports()


if __name__ == '__main__':
    sys.exit(main())
