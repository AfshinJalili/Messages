#!/usr/bin/env python3
"""Generate store/README rasters and the notification bubble from the launcher mark.

Source of truth: app/src/main/res/drawable/ic_launcher_foreground.xml
Colors: commons/src/main/res/values/colors.xml (m3_primary, m3_surface, m3_on_primary)

Writes:
  graphics/icon.svg
  graphics/icon-512.png
  graphics/icon-1024.png
  graphics/icon.webp
  app/src/main/ic_launcher-playstore.png
  app/src/main/res/drawable/ic_message_bubble.xml

Pass --check to verify committed outputs match a fresh export (no writes).
Requires system Python packages gi (Rsvg 2.0) and Pillow.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FOREGROUND = ROOT / 'app/src/main/res/drawable/ic_launcher_foreground.xml'
COLORS = ROOT / 'commons/src/main/res/values/colors.xml'
GRAPHICS = ROOT / 'graphics'
BUBBLE = ROOT / 'app/src/main/res/drawable/ic_message_bubble.xml'
PLAYSTORE = ROOT / 'app/src/main/ic_launcher-playstore.png'

# Notification viewport crops the adaptive-icon padding around the mark path.
BUBBLE_VIEW = 76
BUBBLE_TRANSLATE = (-12, -7)


def _attr(tag: str, name: str) -> str:
    match = re.search(rf'\bandroid:{name}="([^"]+)"', tag)
    if not match:
        raise ValueError(f'missing android:{name} in {tag[:80]}…')
    return match.group(1)


def parse_foreground(text: str) -> tuple[float, float, float, float, str]:
    """Return translateX, translateY, scaleX, scaleY, pathData from the brand vector."""
    group = re.search(r'<group\b[^>]*>', text)
    path = re.search(r'<path\b[^>]*/?>', text)
    if not group or not path:
        raise ValueError(f'{FOREGROUND.relative_to(ROOT)}: expected one <group> and one <path>')
    if len(re.findall(r'<path\b', text)) != 1:
        raise ValueError(f'{FOREGROUND.relative_to(ROOT)}: brand mark must be a single path')
    g, p = group.group(0), path.group(0)
    return (
        float(_attr(g, 'translateX')),
        float(_attr(g, 'translateY')),
        float(_attr(g, 'scaleX')),
        float(_attr(g, 'scaleY')),
        _attr(p, 'pathData'),
    )


def parse_colors(text: str) -> dict[str, str]:
    found = dict(re.findall(r'<color\s+name="(m3_(?:primary|surface|on_primary))">(#[0-9A-Fa-f]{6})</color>', text))
    for name in ('m3_primary', 'm3_surface', 'm3_on_primary'):
        if name not in found:
            raise ValueError(f'{COLORS.relative_to(ROOT)}: missing {name}')
    return found


def _num(value: float) -> str:
    return str(int(value)) if value == int(value) else str(value)


def build_icon_svg(path_data: str, tx: float, ty: float, sx: float, sy: float, colors: dict[str, str]) -> str:
    # Adaptive preview: primary plate + surface mark with the same padding as the vector.
    transform = f'translate({_num(tx)} {_num(ty)}) scale({_num(sx)} {_num(sy)})'
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 108 108">\n'
        f'  <rect width="108" height="108" fill="{colors["m3_primary"]}"/>\n'
        f'  <g transform="{transform}">\n'
        f'    <path fill="{colors["m3_surface"]}" fill-rule="evenodd" d="{path_data}"/>\n'
        '  </g>\n'
        '</svg>\n'
    )


def build_bubble_xml(path_data: str) -> str:
    dx, dy = BUBBLE_TRANSLATE
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by tools/export_icon.py from ic_launcher_foreground.xml. Do not edit. -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="24dp"\n'
        '    android:height="24dp"\n'
        f'    android:viewportWidth="{BUBBLE_VIEW}"\n'
        f'    android:viewportHeight="{BUBBLE_VIEW}">\n'
        f'    <group android:translateX="{dx}" android:translateY="{dy}">\n'
        '        <path\n'
        '            android:fillColor="@color/m3_on_primary"\n'
        '            android:fillType="evenOdd"\n'
        f'            android:pathData="{path_data}" />\n'
        '    </group>\n'
        '</vector>\n'
    )


def render_png(svg: str, size: int, dest: Path) -> None:
    import gi
    gi.require_version('Rsvg', '2.0')
    from gi.repository import Rsvg

    sized = svg.replace('width="512" height="512"', f'width="{size}" height="{size}"', 1)
    Rsvg.Handle.new_from_data(sized.encode()).get_pixbuf().savev(str(dest), 'png', [], [])


def planned_outputs(path_data: str, tx: float, ty: float, sx: float, sy: float, colors: dict[str, str]) -> dict[Path, str | bytes]:
    from PIL import Image
    import io

    svg = build_icon_svg(path_data, tx, ty, sx, sy, colors)
    bubble = build_bubble_xml(path_data)

    # Rasterize into memory for --check without touching the tree mid-compare.
    tmp_1024 = GRAPHICS / '.icon-1024.export.png'
    tmp_512 = GRAPHICS / '.icon-512.export.png'
    GRAPHICS.mkdir(parents=True, exist_ok=True)
    render_png(svg, 1024, tmp_1024)
    render_png(svg, 512, tmp_512)
    try:
        png_1024 = tmp_1024.read_bytes()
        png_512 = tmp_512.read_bytes()
        with Image.open(tmp_1024) as image:
            buf = io.BytesIO()
            image.resize((192, 192), Image.Resampling.LANCZOS).save(buf, format='WEBP', lossless=True)
            webp = buf.getvalue()
    finally:
        tmp_1024.unlink(missing_ok=True)
        tmp_512.unlink(missing_ok=True)

    return {
        GRAPHICS / 'icon.svg': svg,
        GRAPHICS / 'icon-1024.png': png_1024,
        GRAPHICS / 'icon-512.png': png_512,
        GRAPHICS / 'icon.webp': webp,
        PLAYSTORE: png_512,
        BUBBLE: bubble,
    }


def export(*, check: bool) -> int:
    tx, ty, sx, sy, path_data = parse_foreground(FOREGROUND.read_text())
    colors = parse_colors(COLORS.read_text())
    outputs = planned_outputs(path_data, tx, ty, sx, sy, colors)

    if check:
        failed = []
        for path, content in outputs.items():
            if not path.exists():
                failed.append(f'missing {path.relative_to(ROOT)}')
                continue
            existing = path.read_bytes() if isinstance(content, bytes) else path.read_text()
            if existing != content:
                failed.append(f'stale {path.relative_to(ROOT)} (run python3 tools/export_icon.py)')
        if failed:
            print('Icon export check failed:', file=sys.stderr)
            for line in failed:
                print(f'  {line}', file=sys.stderr)
            return 1
        print('Icon export check passed')
        return 0

    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        if isinstance(content, bytes):
            path.write_bytes(content)
        else:
            path.write_text(content)
        print(f'wrote {path.relative_to(ROOT)}')
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='verify generated assets without writing')
    args = parser.parse_args(argv)
    return export(check=args.check)


if __name__ == '__main__':
    sys.exit(main())
