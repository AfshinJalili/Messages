#!/usr/bin/env python3
"""Generate the Lucide interface icons used by design/open-line.pen as vector drawables.

Lucide (ISC) is not vendored. Point the script at an unpacked lucide-static package:

    npm pack lucide-static@1.48.0 && tar xzf lucide-static-1.48.0.tgz
    python3 tools/export_ui_icons.py package/icons

Each icon in ICONS becomes res/drawable/ic_lucide_<name>.xml, stroked with @color/icon_mask
so Compose and XML tint it. Icons in MIRRORED flip under RTL. --check verifies the committed drawables match the source.
"""
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ICONS = [
    "archive", "arrow-left", "arrow-right", "ban", "bell", "bell-off", "calendar", "check", "check-check",
    "chevron-down", "chevron-right", "circle-dot", "circle-help", "clock", "cloud-off", "contact", "copy",
    "database-backup", "download", "ellipsis-vertical", "eye", "eye-off", "file-text", "hand", "hard-drive",
    "hash", "image", "inbox", "info", "languages", "layers", "list-checks", "lock-keyhole", "mail", "message-circle",
    "message-square-text", "messages-square", "palette", "pencil", "phone", "pin", "plus", "search", "send",
    "settings", "share-2", "shield-alert", "shield-ban", "smartphone", "square-check", "square-pen", "star",
    "text-cursor-input", "trash-2", "triangle-alert", "type", "upload", "user", "user-plus", "users", "volume-2", "x",
]

# Direction-bearing glyphs flip under RTL.
MIRRORED = {"arrow-left", "arrow-right", "chevron-right"}

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "app/src/main/res/drawable"
SVG = "{http://www.w3.org/2000/svg}"


def num(value):
    text = f"{float(value):.3f}".rstrip("0").rstrip(".")
    return "0" if text in ("-0", "") else text


def circle(cx, cy, rx, ry):
    # Two arcs; VectorDrawable has no circle element.
    return (f"M{num(cx - rx)},{num(cy)} a{num(rx)},{num(ry)} 0 1,0 {num(2 * rx)},0 "
            f"a{num(rx)},{num(ry)} 0 1,0 {num(-2 * rx)},0")


def rect(x, y, w, h, rx, ry):
    if not rx and not ry:
        return f"M{num(x)},{num(y)}h{num(w)}v{num(h)}h{num(-w)}z"
    rx = min(rx or ry, w / 2)
    ry = min(ry or rx, h / 2)
    return (f"M{num(x + rx)},{num(y)}h{num(w - 2 * rx)}a{num(rx)},{num(ry)} 0 0,1 {num(rx)},{num(ry)}"
            f"v{num(h - 2 * ry)}a{num(rx)},{num(ry)} 0 0,1 {num(-rx)},{num(ry)}h{num(-(w - 2 * rx))}"
            f"a{num(rx)},{num(ry)} 0 0,1 {num(-rx)},{num(-ry)}v{num(-(h - 2 * ry))}"
            f"a{num(rx)},{num(ry)} 0 0,1 {num(rx)},{num(-ry)}z")


def points(value, close):
    pts = re.findall(r"-?[\d.]+", value)
    pairs = [f"{num(pts[i])},{num(pts[i + 1])}" for i in range(0, len(pts) - 1, 2)]
    return "M" + " L".join(pairs) + (" Z" if close else "")


def path_data(el):
    tag = el.tag.replace(SVG, "")
    a = {k: el.get(k) for k in el.keys()}
    f = lambda k, d=0.0: float(a.get(k, d) or d)
    if tag == "path":
        return a["d"]
    if tag == "circle":
        return circle(f("cx"), f("cy"), f("r"), f("r"))
    if tag == "ellipse":
        return circle(f("cx"), f("cy"), f("rx"), f("ry"))
    if tag == "rect":
        return rect(f("x"), f("y"), f("width"), f("height"), f("rx"), f("ry"))
    if tag == "line":
        return f"M{num(f('x1'))},{num(f('y1'))} L{num(f('x2'))},{num(f('y2'))}"
    if tag in ("polyline", "polygon"):
        return points(a["points"], tag == "polygon")
    raise ValueError(f"unsupported element {tag}")


def drawable(name, source):
    tree = ET.parse(source)
    paths = [path_data(el) for el in tree.getroot().iter() if el.tag != f"{SVG}svg" and el.tag.startswith(SVG)]
    assert paths, f"{name}: no drawable elements"
    body = "".join(
        "    <path\n"
        f'        android:pathData="{p}"\n'
        '        android:strokeWidth="2"\n'
        '        android:strokeColor="@color/icon_mask"\n'
        '        android:strokeLineCap="round"\n'
        '        android:strokeLineJoin="round" />\n'
        for p in paths
    )
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f'<!-- Lucide "{name}" (ISC), generated by tools/export_ui_icons.py. -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="24dp"\n'
        '    android:height="24dp"\n'
        '    android:viewportWidth="24"\n'
        '    android:viewportHeight="24"'
        + ('\n    android:autoMirrored="true">\n' if name in MIRRORED else ">\n")
        + f"{body}</vector>\n"
    )


def target(name):
    return OUT / f"ic_lucide_{name.replace('-', '_')}.xml"


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    check = "--check" in sys.argv
    if not args:
        sys.exit(__doc__)
    icons = Path(args[0])
    stale = []
    for name in ICONS:
        text = drawable(name, icons / f"{name}.svg")
        out = target(name)
        if check:
            if not out.exists() or out.read_text() != text:
                stale.append(out.name)
        else:
            out.write_text(text)
    if stale:
        sys.exit("stale icons: " + ", ".join(stale))
    print(f"{len(ICONS)} icons {'verified' if check else 'written'}")


if __name__ == "__main__":
    main()
